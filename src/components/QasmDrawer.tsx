import React, { useState, useEffect } from 'react';
import { GateOp, parseQasm3 } from '../types/quantum';
import { Code2, Copy, Check, X, Download, Play, Edit3, Eye, AlertCircle } from 'lucide-react';

interface QasmDrawerProps {
  isOpen: boolean;
  onClose: () => void;
  numQubits: number;
  circuit: GateOp[];
  rotAngle: number;
  onImportCircuit?: (numQubits: number, gates: GateOp[]) => void;
}

export const QasmDrawer: React.FC<QasmDrawerProps> = ({
  isOpen,
  onClose,
  numQubits,
  circuit,
  rotAngle,
  onImportCircuit
}) => {
  const [copied, setCopied] = useState(false);
  const [activeTab, setActiveTab] = useState<'view' | 'edit'>('view');
  const [editableCode, setEditableCode] = useState<string>('');
  const [compileError, setCompileError] = useState<string | null>(null);
  const [compileSuccess, setCompileSuccess] = useState<string | null>(null);

  // Generate clean OpenQASM 3.0 code
  const sorted = [...circuit].sort((a, b) => a.step - b.step);
  let code = `// OpenQASM 3.0 specification\n// Generated by Quantum Studio\n\n`;
  code += `OPENQASM 3.0;\ninclude "stdgates.inc";\n\n`;
  code += `qubit[${numQubits}] q;\nbit[${numQubits}] c;\n\n`;

  sorted.forEach(g => {
    const angleVal = (g.angle !== undefined ? g.angle : rotAngle).toFixed(4);
    switch (g.type) {
      case 'H':
        code += `h q[${g.qubit}];\n`;
        break;
      case 'X':
        code += `x q[${g.qubit}];\n`;
        break;
      case 'Y':
        code += `y q[${g.qubit}];\n`;
        break;
      case 'Z':
        code += `z q[${g.qubit}];\n`;
        break;
      case 'S':
        code += `s q[${g.qubit}];\n`;
        break;
      case 'T':
        code += `t q[${g.qubit}];\n`;
        break;
      case 'Sdg':
        code += `sdg q[${g.qubit}];\n`;
        break;
      case 'SX':
        code += `sx q[${g.qubit}];\n`;
        break;
      case 'Rx':
        code += `rx(${angleVal}) q[${g.qubit}];\n`;
        break;
      case 'Ry':
        code += `ry(${angleVal}) q[${g.qubit}];\n`;
        break;
      case 'Rz':
        code += `rz(${angleVal}) q[${g.qubit}];\n`;
        break;
      case 'CNOT':
        code += `cx q[${g.control}], q[${g.target}];\n`;
        break;
      case 'CZ':
        code += `cz q[${g.control}], q[${g.target}];\n`;
        break;
      case 'CY':
        code += `cy q[${g.control}], q[${g.target}];\n`;
        break;
      case 'SWAP':
        code += `swap q[${g.q1}], q[${g.q2}];\n`;
        break;
      case 'ISWAP':
        code += `iswap q[${g.q1}], q[${g.q2}];\n`;
        break;
      case 'CP':
        code += `cphase(${angleVal}) q[${g.control}], q[${g.target}];\n`;
        break;
      case 'CCX':
        code += `ccx q[${g.c1}], q[${g.c2}], q[${g.target}];\n`;
        break;
      case 'CSWAP':
        code += `cswap q[${g.control}], q[${g.t1}], q[${g.t2}];\n`;
        break;
      case 'M':
        code += `c[${g.qubit}] = measure q[${g.qubit}];\n`;
        break;
      default:
        break;
    }
  });

  code += `\n// Barrier & measurement synchronization\nbarrier q;\nc = measure q;\n`;

  useEffect(() => {
    if (isOpen) {
      setEditableCode(code);
      setCompileError(null);
      setCompileSuccess(null);
    }
  }, [isOpen, code]);

  if (!isOpen) return null;

  const handleCopy = () => {
    navigator.clipboard.writeText(activeTab === 'edit' ? editableCode : code);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const textToDownload = activeTab === 'edit' ? editableCode : code;
    const blob = new Blob([textToDownload], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `circuit-${Date.now()}.qasm`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleCompileToCircuit = () => {
    setCompileError(null);
    setCompileSuccess(null);
    const parsed = parseQasm3(editableCode);
    if (parsed.error) {
      setCompileError(parsed.error);
      return;
    }
    if (onImportCircuit) {
      onImportCircuit(parsed.numQubits, parsed.gates);
      setCompileSuccess(`Successfully compiled ${parsed.gates.length} gates across ${parsed.numQubits} qubits into Composer.`);
      setTimeout(() => {
        onClose();
      }, 1200);
    }
  };

  return (
    <div className="fixed inset-0 z-50 bg-black/75 backdrop-blur-xs flex items-center justify-center p-4">
      <div className="bg-[#070e17] border border-cyan-800/50 rounded-2xl max-w-3xl w-full p-6 shadow-2xl flex flex-col max-h-[88vh] font-mono">
        <div className="flex items-center justify-between pb-3 border-b border-slate-800">
          <div className="flex items-center gap-3">
            <div className="w-8 h-8 rounded-lg bg-cyan-950 border border-cyan-500/40 flex items-center justify-center text-cyan-400">
              <Code2 className="w-4 h-4 text-cyan-300" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <span className="text-sm font-bold text-white">OpenQASM 3.0 Interface</span>
                <span className="text-[10px] px-2 py-0.5 rounded bg-cyan-950 text-cyan-300 border border-cyan-800 font-bold uppercase">
                  Bi-Directional
                </span>
              </div>
              <p className="text-[11px] text-slate-400">Export active circuit or compile custom QASM code directly into the workspace</p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <div className="flex items-center bg-slate-950 p-1 rounded-lg border border-slate-800 text-xs">
              <button
                onClick={() => setActiveTab('view')}
                className={`px-3 py-1 rounded transition-colors flex items-center gap-1 cursor-pointer ${
                  activeTab === 'view' ? 'bg-cyan-950 text-cyan-300 font-bold border border-cyan-700/50' : 'text-slate-400 hover:text-white'
                }`}
              >
                <Eye className="w-3.5 h-3.5" />
                <span>Generated Code</span>
              </button>
              <button
                onClick={() => setActiveTab('edit')}
                className={`px-3 py-1 rounded transition-colors flex items-center gap-1 cursor-pointer ${
                  activeTab === 'edit' ? 'bg-cyan-950 text-cyan-300 font-bold border border-cyan-700/50' : 'text-slate-400 hover:text-white'
                }`}
              >
                <Edit3 className="w-3.5 h-3.5" />
                <span>Editor &amp; Import</span>
              </button>
            </div>

            <button
              onClick={onClose}
              className="p-1 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 cursor-pointer"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {compileError && (
          <div className="mt-3 p-3 rounded-xl bg-rose-950/70 border border-rose-600/50 text-rose-200 text-xs flex items-center gap-2">
            <AlertCircle className="w-4 h-4 shrink-0 text-rose-400" />
            <span>{compileError}</span>
          </div>
        )}

        {compileSuccess && (
          <div className="mt-3 p-3 rounded-xl bg-emerald-950/70 border border-emerald-600/50 text-emerald-200 text-xs flex items-center gap-2">
            <Check className="w-4 h-4 shrink-0 text-emerald-400" />
            <span>{compileSuccess}</span>
          </div>
        )}

        {activeTab === 'view' ? (
          <div className="flex-1 overflow-y-auto my-4 bg-[#03060c] p-4 rounded-xl border border-slate-800 text-xs text-cyan-200/90 leading-relaxed whitespace-pre selection:bg-cyan-900 selection:text-white">
            {code}
          </div>
        ) : (
          <div className="flex-1 my-4 flex flex-col min-h-64">
            <textarea
              value={editableCode}
              onChange={(e) => setEditableCode(e.target.value)}
              placeholder="Paste or write your OpenQASM 3.0 code here..."
              className="flex-1 w-full bg-[#03060c] p-4 rounded-xl border border-cyan-800/40 text-xs text-cyan-200/90 leading-relaxed focus:outline-hidden focus:border-cyan-400 font-mono resize-none selection:bg-cyan-900 selection:text-white"
            />
          </div>
        )}

        <div className="flex items-center justify-between pt-3 border-t border-slate-800">
          <span className="text-[11px] text-slate-500">
            Compliant with IBM Qiskit, AWS Braket, and OpenQASM 3.0 standard gates
          </span>
          <div className="flex items-center gap-2">
            {activeTab === 'edit' && onImportCircuit && (
              <button
                onClick={handleCompileToCircuit}
                className="px-3.5 py-1.5 rounded-lg bg-emerald-500 hover:bg-emerald-400 text-slate-950 font-bold text-xs flex items-center gap-1.5 cursor-pointer shadow-md shadow-emerald-500/20"
              >
                <Play className="w-3.5 h-3.5 fill-current" />
                <span>Compile to Composer</span>
              </button>
            )}

            <button
              onClick={handleDownload}
              className="px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 text-xs flex items-center gap-1.5 cursor-pointer"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download .qasm</span>
            </button>

            <button
              onClick={handleCopy}
              className="px-3.5 py-1.5 rounded-lg bg-cyan-500 hover:bg-cyan-400 text-slate-950 font-bold text-xs flex items-center gap-1.5 cursor-pointer shadow-md shadow-cyan-500/20"
            >
              {copied ? <Check className="w-3.5 h-3.5" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied!' : 'Copy Code'}</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};

